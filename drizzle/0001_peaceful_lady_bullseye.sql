CREATE TABLE `operational_records` (
	`id` text PRIMARY KEY NOT NULL,
	`version_id` text NOT NULL,
	`source` text NOT NULL,
	`source_row` integer NOT NULL,
	`status` text,
	`wbs` text,
	`operation` text,
	`material` text,
	`product` text,
	`center` text,
	`farm` text,
	`field` text,
	`harvest` text,
	`scheduled_date` text,
	`execution_date` text,
	`quantity` real,
	`unit` text,
	`area` real,
	`is_excluded` integer DEFAULT false NOT NULL,
	`raw` text NOT NULL,
	`created_at` text DEFAULT CURRENT_TIMESTAMP NOT NULL,
	FOREIGN KEY (`version_id`) REFERENCES `import_versions`(`id`) ON UPDATE no action ON DELETE no action
);
